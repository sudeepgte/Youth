    function startTimer() {
        var endsAtStr =  null;
        if (!endsAtStr) {
            document.getElementById('battle-timer').textContent = 'ÃƒÆ’Ã‚Â¢Ãƒâ€¹Ã¢â‚¬Â Ãƒâ€¦Ã‚Â¾';
            return;
        }
        var endsAt = new Date(endsAtStr).getTime();

        function updateTimer() {
            var now = new Date().getTime();
            var diff = endsAt - now;
            if (diff <= 0) {
                document.getElementById('battle-timer').textContent = '00:00';
                
                // Auto-end battle when timer reaches 0
                if (!window.battleEndedTriggered) {
                    window.battleEndedTriggered = true;
                    endBattle(true);
                }
                return;
            }
            var hours = Math.floor(diff / 3600000);
            var minutes = Math.floor((diff % 3600000) / 60000);
            var seconds = Math.floor((diff % 60000) / 1000);
            if (hours > 0) {
                document.getElementById('battle-timer').textContent =
                    String(hours).padStart(2, '0') + ':' +
                    String(minutes).padStart(2, '0') + ':' +
                    String(seconds).padStart(2, '0');
            } else {
                document.getElementById('battle-timer').textContent =
                    String(minutes).padStart(2, '0') + ':' +
                    String(seconds).padStart(2, '0');
            }
        }

        updateTimer();
        setInterval(updateTimer, 1000);
    }
