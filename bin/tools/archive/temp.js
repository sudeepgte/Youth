    function sendComment() {
        var input = document.getElementById('chat-input');
        var msg = input.value.trim();
        if (!msg || !stompClient) return;
        stompClient.send('/app/battle/' + battleId + '/comment', {},
            JSON.stringify({ message: msg }));
        input.value = '';
    }

